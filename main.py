from google import genai
import time


# ============================================================
# НАСТРОЙКИ
# ============================================================

client = genai.Client()

MODEL = "gemini-3.6-flash"


# ============================================================
# ОБЩАЯ ФУНКЦИЯ ДЛЯ ЗАПРОСА К GEMINI
# ============================================================

def ask_gemini(prompt, attempts=3):

    for attempt in range(1, attempts + 1):

        try:

            response = client.models.generate_content(
                model=MODEL,
                contents=prompt
            )

            return response.text

        except Exception as error:

            print()
            print(f"Ошибка API. Попытка {attempt}/{attempts}")
            print(error)

            # Если попытка не последняя — ждём и пробуем ещё раз
            if attempt < attempts:

                print("Повторяем запрос через 5 секунд...")
                time.sleep(5)

    print()
    print("Не удалось получить ответ после нескольких попыток.")

    return None


# ============================================================
# ЗАДАЧА
# ============================================================

task = """
В магазине есть 3 коробки:

1. «Яблоки»
2. «Апельсины»
3. «Яблоки и апельсины»

Известно, что ВСЕ этикетки наклеены неправильно.

Можно достать только ОДИН фрукт из ОДНОЙ коробки,
не заглядывая внутрь.

Как определить, что находится в каждой коробке?
Объясни решение.
"""


# ============================================================
# ВАРИАНТ 1 — ПРЯМОЙ ОТВЕТ
# ============================================================

def direct_answer():

    answer = ask_gemini(task)

    print()
    print("=" * 60)
    print("1. ПРЯМОЙ ОТВЕТ")
    print("=" * 60)

    if answer:
        print(answer)
    else:
        print("Не удалось получить ответ.")


# ============================================================
# ВАРИАНТ 2 — ПОШАГОВОЕ РЕШЕНИЕ
# ============================================================

def step_by_step():

    prompt = f"""
{task}

Решай задачу пошагово.

Объясни:
1. Из какой коробки нужно достать фрукт.
2. Что означает каждый возможный результат.
3. Как после этого определить содержимое остальных коробок.
4. В конце дай чёткий итоговый ответ.

Пиши понятно и последовательно.
"""

    answer = ask_gemini(prompt)

    print()
    print("=" * 60)
    print("2. ПОШАГОВОЕ РЕШЕНИЕ")
    print("=" * 60)

    if answer:
        print(answer)
    else:
        print("Не удалось получить ответ.")


# ============================================================
# ВАРИАНТ 3 — МОДЕЛЬ СНАЧАЛА СОЗДАЁТ ПРОМПТ
# ============================================================

def prompt_generation():

    prompt_creator = f"""
Тебе дана логическая задача:

{task}

Составь эффективный промпт для другой LLM,
который поможет решить эту задачу точно и понятно.

Промпт должен:

- содержать полное условие задачи;
- попросить внимательно проанализировать условия;
- попросить учитывать тот факт, что все этикетки неправильные;
- попросить указать, из какой коробки нужно достать фрукт;
- попросить рассмотреть оба возможных результата;
- попросить проверить решение;
- попросить дать понятное пошаговое объяснение.

Выведи только готовый промпт без дополнительного объяснения.
"""

    # --------------------------------------------------------
    # Первый запрос:
    # модель создаёт промпт
    # --------------------------------------------------------

    generated_prompt = ask_gemini(prompt_creator)

    print()
    print("=" * 60)
    print("3. ПРОМПТ, СОЗДАННЫЙ МОДЕЛЬЮ")
    print("=" * 60)

    if not generated_prompt:

        print("Не удалось создать промпт.")

        return

    print(generated_prompt)

    # --------------------------------------------------------
    # Пауза перед вторым запросом
    # --------------------------------------------------------

    print()
    print("Ждём 3 секунды перед следующим запросом...")
    time.sleep(3)

    # --------------------------------------------------------
    # Второй запрос:
    # используем созданный промпт
    # --------------------------------------------------------

    answer = ask_gemini(generated_prompt)

    print()
    print("=" * 60)
    print("3. РЕШЕНИЕ С ПОМОЩЬЮ СОЗДАННОГО ПРОМПТА")
    print("=" * 60)

    if answer:
        print(answer)
    else:
        print("Не удалось получить решение.")


# ============================================================
# ВАРИАНТ 4 — ГРУППА ЭКСПЕРТОВ
# ============================================================

def experts():

    prompt = f"""
Реши следующую логическую задачу:

{task}

Представь группу из трёх экспертов.

АНАЛИТИК:
Проанализируй условия задачи.
Определи правильную стратегию решения.

ИНЖЕНЕР:
Реши задачу самостоятельно.
Особое внимание удели последовательности действий.

КРИТИК:
Проверь решение аналитика и инженера.
Найди возможные ошибки.
Проверь, что все этикетки действительно остаются неправильными.

После анализа дай финальный правильный вывод.

Ответ раздели на три части:

1. АНАЛИТИК
2. ИНЖЕНЕР
3. КРИТИК И ИТОГ
"""

    answer = ask_gemini(prompt)

    print()
    print("=" * 60)
    print("4. ГРУППА ЭКСПЕРТОВ")
    print("=" * 60)

    if answer:
        print(answer)
    else:
        print("Не удалось получить ответ.")


